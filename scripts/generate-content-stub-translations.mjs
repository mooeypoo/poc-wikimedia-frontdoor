#!/usr/bin/env node

/**
 * Writes pseudo-localized stub catalogues for the prose content experiment.
 *
 * PROTOTYPE TOOL. These are not translations and must never be mistaken for
 * them. The point is to demonstrate that the pipeline produces per-locale files
 * for however many locales have a catalogue, without waiting on real
 * translation work — `@wikimedia/banana-content` derives its output locales
 * purely from the `i18n/content/*.json` files that exist, so a stub catalogue
 * is all it takes to bring a locale into the demo.
 *
 * Pseudo-localization rather than copied English is deliberate. Copied English
 * would render a page that *looks* translated and is not, which is exactly the
 * confusion worth avoiding; accented text is visibly non-English at a glance,
 * proves the string travelled through the catalogue rather than being baked
 * into the page, and makes an unmarked string obvious.
 *
 * Safety: a stub file carries `@metadata.stub: true`. This script refuses to
 * overwrite any catalogue lacking that marker, so it can never destroy real
 * translation work — including the hand-written `he` and `es` fixtures.
 *
 * Usage:
 *   npm run generate-content-i18n-stubs          # write stubs, then re-run the generator
 *   npm run generate-content-i18n-stubs -- --remove
 */

import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { readFile, writeFile, readdir, unlink } from 'node:fs/promises'
// The accessor, not the generated catalog: the UI resolves languages through
// config/languages.ts, so anything that decides which locales the demo shows
// must resolve them the same way, LANGUAGE_OVERRIDES included.
import { getLanguageByCode } from '../config/languages.ts'

const projectRoot = dirname( dirname( fileURLToPath( import.meta.url ) ) )
const messagesDirectory = join( projectRoot, 'i18n', 'content' )

/**
 * Locales to stub. Deliberately left-to-right: pseudo-localized text is Latin
 * script, so stubbing a right-to-left locale would render a page whose content
 * fights its own direction. Real right-to-left coverage comes from the
 * hand-written Hebrew fixture instead.
 */
const STUB_LOCALES = [ 'fr', 'de', 'it', 'nl', 'pt' ]

/** Marker distinguishing a generated stub from translator work. */
const STUB_MARKER = 'stub'

const STUB_NOTE =
	'PSEUDO-LOCALIZED STUB, NOT A TRANSLATION. Generated by ' +
	'scripts/generate-content-stub-translations.mjs to demonstrate per-locale ' +
	'output. Delete this file, or run the script with --remove, before real ' +
	'translations for this locale arrive.'

/** Latin letters mapped to accented look-alikes. */
const ACCENTS = {
	a: 'à', b: 'ƀ', c: 'ç', d: 'ð', e: 'é', f: 'ƒ', g: 'ĝ', h: 'ĥ', i: 'í',
	j: 'ĵ', k: 'ķ', l: 'ĺ', m: 'ɱ', n: 'ñ', o: 'ö', p: 'þ', q: ' q', r: 'ŕ',
	s: 'š', t: 'ť', u: 'ü', v: 'ṽ', w: 'ŵ', x: 'ẋ', y: 'ý', z: 'ž',
	A: 'À', B: 'Ɓ', C: 'Ç', D: 'Ð', E: 'É', F: 'Ƒ', G: 'Ĝ', H: 'Ĥ', I: 'Í',
	J: 'Ĵ', K: 'Ķ', L: 'Ĺ', M: 'Ɱ', N: 'Ñ', O: 'Ö', P: 'Þ', Q: 'Q', R: 'Ŕ',
	S: 'Š', T: 'Ť', U: 'Ü', V: 'Ṽ', W: 'Ŵ', X: 'Ẋ', Y: 'Ý', Z: 'Ž'
}

/**
 * Segments that must survive untouched: banana magic words and parameters,
 * and the URL half of a Markdown link. Accenting any of them would change
 * behaviour rather than appearance.
 */
const PROTECTED = /(\{\{[^}]*\}\}|\]\([^)]*\)|\$\d)/g

/**
 * Pseudo-localizes one message.
 *
 * @param {string} value - Source-language message.
 * @returns {string} Visibly non-English text with markup and parameters intact.
 */
function pseudoLocalize( value ) {
	return '⟦' + value
		.split( PROTECTED )
		.map( ( piece, index ) => (
			// Odd indices are the captured protected segments.
			index % 2 === 1 ?
				piece :
				piece.replace( /[a-zA-Z]/g, ( letter ) => ACCENTS[ letter ] ?? letter )
		) )
		.join( '' ) + '⟧'
}

/**
 * Reads a catalogue, returning null when absent.
 *
 * @param {string} path - File to read.
 * @returns {Promise<object|null>}
 */
async function readCatalog( path ) {
	try {
		return JSON.parse( await readFile( path, 'utf-8' ) )
	} catch {
		return null
	}
}

/**
 * Whether a catalogue is one of ours and therefore safe to replace.
 *
 * @param {object|null} catalog - Parsed catalogue, or null when absent.
 * @returns {boolean}
 */
function isStub( catalog ) {
	return catalog?.[ '@metadata' ]?.[ STUB_MARKER ] === true
}

/**
 * Removes every stub catalogue, leaving real translations alone.
 *
 * @returns {Promise<void>}
 */
async function removeStubs() {
	for ( const entry of ( await readdir( messagesDirectory ) ).sort() ) {
		if ( !entry.endsWith( '.json' ) ) {
			continue
		}
		const path = join( messagesDirectory, entry )
		if ( isStub( await readCatalog( path ) ) ) {
			await unlink( path )
			console.log( `✓ removed i18n/content/${ entry }` )
		}
	}
	console.log( '\nRe-run `npm run generate-content-i18n` to drop the generated pages.' )
}

/**
 * Writes the stub catalogues.
 *
 * @returns {Promise<number>} Exit code.
 */
async function writeStubs() {
	const englishPath = join( messagesDirectory, 'en.json' )
	const english = await readCatalog( englishPath )
	if ( !english ) {
		console.error(
			'✗ i18n/content/en.json not found. Run `npm run generate-content-i18n` first — ' +
			'stubs are derived from the extracted English catalogue.'
		)
		return 1
	}

	const messages = Object.entries( english ).filter( ( [ key ] ) => !key.startsWith( '@' ) )
	let failed = false

	for ( const locale of STUB_LOCALES ) {
		const language = getLanguageByCode( locale )
		if ( !language ) {
			console.error( `✗ "${ locale }" is not in the language catalog — skipping` )
			failed = true
			continue
		}
		if ( language.dir !== 'ltr' ) {
			// Pseudo-localized text is Latin script, so a right-to-left stub would
			// render a page whose content fights its own direction. Direction comes
			// from the catalog rather than a hardcoded list, so this stays correct
			// if an override changes it.
			console.error(
				`✗ "${ locale }" is ${ language.dir }; pseudo-localized stubs are Latin script — ` +
				'use a hand-written fixture for right-to-left coverage'
			)
			failed = true
			continue
		}

		const path = join( messagesDirectory, `${ locale }.json` )
		const existing = await readCatalog( path )
		if ( existing && !isStub( existing ) ) {
			// The whole point of the marker: never overwrite translator work.
			console.error(
				`✗ i18n/content/${ locale }.json exists and is not a stub — refusing to ` +
				'overwrite a real translation'
			)
			failed = true
			continue
		}

		const catalog = { '@metadata': { [ STUB_MARKER ]: true, note: STUB_NOTE } }
		for ( const [ key, value ] of messages ) {
			catalog[ key ] = pseudoLocalize( value )
		}
		await writeFile( path, JSON.stringify( catalog, null, 2 ) + '\n', 'utf-8' )
		console.log( `✓ i18n/content/${ locale }.json (${ messages.length } stubs)` )
	}

	console.log( '\nRun `npm run generate-content-i18n` to generate pages for these locales.' )
	return failed ? 1 : 0
}

const remove = process.argv.slice( 2 ).includes( '--remove' )
process.exitCode = remove ? ( await removeStubs(), 0 ) : await writeStubs()
